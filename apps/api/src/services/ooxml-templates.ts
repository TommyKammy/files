/**
 * Builds a minimal, valid OOXML ZIP package for `.docx`, `.xlsx`, or `.pptx`.
 */
export function buildMinimalOfficeDocument(
  kind: OfficeDocumentKind,
  now = new Date()
): BuiltOfficeDocument {
  const bytes =
    kind === 'docx'
      ? buildDocxBytes(now)
      : kind === 'xlsx'
        ? buildXlsxBytes(now)
        : buildPptxBytes(now);

  return {
    bytes,
    mimeType: OFFICE_MIME_TYPES[kind],
    extension: kind,
  };
}
